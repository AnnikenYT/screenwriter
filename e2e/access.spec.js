test('reviewers type inline proposals and comments without changing accepted source', async ({ page, context, browser }) => {
  const owner = actor('review-owner@example.com'), reviewer = actor('reviewer@example.com')
  const { id } = await owner.json('/api/documents', 'POST', { title: 'Review only', text })
  await invite(owner, id, reviewer.user.email, 'reviewer')
  await reviewer.login(context)
  const other = await browser.newContext()
  try {
    await owner.login(other)
    const tab = await other.newPage()
    await tab.goto(`${base}/?document=${id}`)
    await expect(editor(tab)).toBeVisible()
    await page.goto(`${base}/?document=${id}`)
    await expect(editor(page)).toBeVisible()
    await expect(page.getByRole('textbox', { name: 'Document title' })).toBeDisabled()
    await editor(page).focus()
    await page.keyboard.press('Control+End')
    await page.keyboard.type('A proposed beat.', { delay: 15 })
    await expect.poll(() => proposals(tab)).toBe('A proposed beat.')
    await expect.poll(() => proposals(page)).toBe('A proposed beat.')
    expect(await (await owner.call(`/api/documents/${id}/export.fountain`)).text()).toBe(text)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await expect.poll(() => proposals(tab)).toBe('')
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await expect.poll(() => proposals(tab)).toBe('A proposed beat.')
    await page.keyboard.press('Backspace')
    await expect.poll(() => proposals(tab)).toBe('A proposed beat')
    await page.getByRole('button', { name: 'Add comment', exact: true }).click()
    const composer = page.getByRole('dialog', { name: 'New line comment' })
    await composer.locator('textarea').fill('A reviewer note')
    await composer.getByRole('button', { name: 'Post comment', exact: true }).click()
    await expect(tab.getByText('A reviewer note', { exact: true })).toBeVisible()
    await page.reload()
    await expect.poll(() => proposals(page)).toBe('A proposed beat')
  } finally { await other.close() }
})

