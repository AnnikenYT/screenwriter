test('failed reviewer requests keep the proposed text available to copy', async ({ page, context }) => {
  const owner = actor('draft-owner@example.com'), reviewer = actor('draft-reviewer@example.com')
  const { id } = await owner.json('/api/documents', 'POST', { title: 'Unsaved review', text })
  await invite(owner, id, reviewer.user.email, 'reviewer')
  await reviewer.login(context)
  await page.route('**/api/documents/*/review', route => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ error: 'The review changed' }) }))
  await page.goto(`${base}/?document=${id}`)
  await expect(editor(page)).toBeVisible()
  await editor(page).focus()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Keep this draft.')
  await expect(page.getByRole('dialog', { name: 'Unsaved suggestion' })).toBeVisible()
  await expect(page.getByLabel('Unsaved proposed text')).toHaveValue(text + 'Keep this draft.')
  expect(await (await owner.call(`/api/documents/${id}/export.fountain`)).text()).toBe(text)
})

test('non-owners can leave and old grants do not return at the next login', async ({ page, context }) => {
  const owner = actor('leave-owner@example.com'), member = actor('leaving@example.com')
  const { id } = await owner.json('/api/documents', 'POST', { title: 'Leave this screenplay', text })
  await invite(owner, id, member.user.email, 'editor', { canExport: true })
  await member.login(context)
  await page.goto(`${base}/?document=${id}`)
  await expect(editor(page)).toBeVisible()
  await page.getByRole('button', { name: 'Share screenplay', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Leave screenplay', exact: true }).click()
  await expect(page.locator('.room-unavailable')).toBeVisible()
  expect((await member.call(`/api/documents/${id}`)).status).toBe(404)
  actor(member.user.email)
  expect((await member.call(`/api/documents/${id}`)).status).toBe(404)
  await invite(owner, id, member.user.email, 'viewer')
  await page.reload()
  await expect(editor(page)).toHaveAttribute('contenteditable', 'false')
})
