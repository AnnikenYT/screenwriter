import { test, expect } from '@playwright/test'
import { mkdtemp, rm } from 'node:fs/promises'
import { randomBytes } from 'node:crypto'
import { DatabaseSync } from 'node:sqlite'
import { createWorkspace } from '../server/index.js'
import { createAccess, digest } from '../server/access.js'

const base = 'http://localhost:3214'
let directory, workspace, db, identities
test.beforeAll(async () => {
  directory = await mkdtemp('/tmp/screenwriter/screenwriter-acl-browser-')
  workspace = createWorkspace({ DATA_DIR: directory, AUTH_MODE: 'oauth', PUBLIC_URL: base })
  await new Promise(resolve => workspace.server.listen(3214, '127.0.0.1', resolve))
  db = new DatabaseSync(`${directory}/workspace.sqlite`)
  identities = createAccess(db, { mode: 'oauth', publicURL: new URL(base) })
})
test.afterAll(async () => { db?.close(); await workspace?.close(); if (directory) await rm(directory, { recursive: true, force: true }) })

function actor(email) {
  const user = identities.account({ iss: 'https://issuer.test', sub: email, email, email_verified: true, name: email.split('@')[0] })
  const token = randomBytes(32).toString('base64url')
  db.prepare('INSERT INTO sessions VALUES(?,?,?)').run(digest(token), JSON.stringify(user), Date.now() + 86400000)
  return {
    user, token,
    async login(context) { await context.addCookies([{ name: 'screenplay_session', value: token, url: base }]) },
    async call(path, method = 'GET', body) {
      return fetch(base + path, { method, headers: { cookie: `screenplay_session=${token}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) })
    },
    async json(path, method = 'GET', body) {
      const response = await this.call(path, method, body)
      expect(response.ok, `${response.status} ${await response.clone().text()}`).toBe(true)
      return response.json()
    },
  }
}
const text = 'INT. ROOM - DAY\n\nMARA\nHello.\n'
async function invite(owner, id, email, role, flags = {}) {
  return owner.json(`/api/documents/${id}/shares`, 'POST', { kind: 'user', email, role, canInvite: false, canExport: false, ...flags })
}
const editor = page => page.getByRole('textbox', { name: 'Screenplay editor' })
const proposals = page => page.locator('.inline-suggestion-replacement').evaluateAll(nodes => nodes.map(node => node.textContent).join(''))

test('personal workspaces and sharing dialog support invitations before first login', async ({ page, context, browser }) => {
  const owner = actor('workspace-owner@example.com')
  const { id } = await owner.json('/api/documents', 'POST', { title: 'A private screenplay', text })
  await owner.login(context)
  await page.goto(`${base}/?document=${id}`)
  await expect(editor(page)).toBeVisible()
  await page.getByRole('button', { name: 'Share screenplay', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Share screenplay' })
  await dialog.getByLabel('Email', { exact: true }).fill('future-reader@example.com')
  await dialog.getByLabel('Role', { exact: true }).selectOption('viewer')
  await dialog.getByRole('button', { name: 'Invite', exact: true }).click()
  await expect(dialog.locator('.share-grant')).toContainText('future-reader@example.com')
  const reader = actor('future-reader@example.com')
  const other = await browser.newContext()
  try {
    await reader.login(other)
    const tab = await other.newPage()
    await tab.goto(`${base}/?document=${id}`)
    await expect(editor(tab)).toHaveAttribute('contenteditable', 'false')
    await expect(tab.getByRole('button', { name: 'Export', exact: true })).toHaveCount(0)
    await expect(tab.getByRole('button', { name: 'Add comment', exact: true })).toHaveCount(0)
    await tab.getByRole('button', { name: 'Open documents', exact: true }).click()
    await tab.getByRole('button', { name: 'Shared with me', exact: true }).click()
    await expect(tab.locator('.document-dropdown')).toContainText('A private screenplay')
    await tab.getByRole('button', { name: 'My screenplays', exact: true }).click()
    await expect(tab.locator('.document-dropdown')).not.toContainText('A private screenplay')
  } finally { await other.close() }
})

