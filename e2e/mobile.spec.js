import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
const script = 'INT. LIGHTHOUSE - NIGHT\n\nMARA\nPlease remember.\n\nELI\nI will remember.\n'
const screenplay = page => page.getByRole('textbox', { name: 'Screenplay editor' })
async function open(page, request) {
  const response = await request.post('/api/documents', { data: { title: 'A quiet place', text: script } })
  expect(response.ok()).toBe(true)
  const document = await response.json()
  await page.goto(`/?document=${document.id}`)
  await expect(screenplay(page)).toBeVisible()
  return document
}

test('phone writing is full width with readable text and finger-sized controls', async ({ page, request }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page, request)
  const editor = screenplay(page)
  expect((await editor.boundingBox()).width).toBeGreaterThan(330)
  expect(await editor.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16)
  for (const name of ['Bold', 'Italic', 'Underline', 'Add comment']) {
    const box = await page.getByRole('button', { name, exact: true }).boundingBox()
    expect(box.width).toBeGreaterThanOrEqual(44)
    expect(box.height).toBeGreaterThanOrEqual(44)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect(await page.locator('.live-editor .cm-scroller').evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(2)
  await page.screenshot({ path: '/tmp/screenwriter/screenwriter-phone-writing.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Preview', exact: true }).tap()
  await expect(editor).toBeHidden()
  const preview = page.getByLabel('Rendered screenplay')
  await expect(preview).toBeVisible()
  expect((await preview.boundingBox()).width).toBeGreaterThan(380)
  await expect(preview).toContainText('Please remember.')
  await page.getByRole('button', { name: 'Write', exact: true }).tap()
  await expect(editor).toBeFocused()
  expect(errors).toEqual([])
})

test('touch formatting and tools preserve the editing selection and undo history', async ({ page, request }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await open(page, request)
  await screenplay(page).focus()
  await page.keyboard.press('Control+End')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('End')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Control+Shift+ArrowLeft')
  await page.getByRole('button', { name: 'Bold', exact: true }).tap()
  await expect(screenplay(page)).toContainText('**remember**')
  await expect(screenplay(page)).toBeFocused()
  await page.getByRole('button', { name: 'Open tools', exact: true }).tap()
  const tools = page.getByRole('dialog', { name: 'Workspace tools' })
  await expect(tools).toBeVisible()
  await tools.getByRole('button', { name: 'Characters', exact: true }).tap()
  await expect(tools.getByRole('button', { name: 'MARA Character sheet' })).toBeVisible()
  await page.screenshot({ path: '/tmp/screenwriter/screenwriter-phone-tools.png', animations: 'disabled' })
  await tools.getByRole('button', { name: 'Close tools', exact: true }).tap()
  await expect(screenplay(page)).toBeFocused()
  expect(await page.evaluate(() => window.getSelection().toString())).toBe('remember')
  await page.getByRole('button', { name: 'Italic', exact: true }).tap()
  await expect(screenplay(page)).toContainText('***remember***')
  await page.getByRole('button', { name: 'Undo', exact: true }).tap()
  await expect(screenplay(page)).toContainText('**remember**')
  expect(errors).toEqual([])
})

test('phone screenplay shortcuts choose names, complete prefixes and insert asides', async ({ page, request }) => {
  await open(page, request)
  await screenplay(page).focus()
  await page.keyboard.press('Control+End')
  await page.getByRole('button', { name: 'Character', exact: true }).tap()
  const characters = page.getByRole('dialog', { name: 'Choose a character' })
  await expect(characters).toBeVisible()
  expect(await characters.getByLabel('Character name').evaluate(el => getComputedStyle(el).fontSize)).toBe('16px')
  await characters.getByRole('button', { name: 'ELI', exact: true }).tap()
  await expect(screenplay(page)).toBeFocused()
  await page.keyboard.type('We should go.')
  await expect(screenplay(page)).toContainText('@ELI')
  await page.getByRole('button', { name: '(Aside)', exact: true }).tap()
  await page.keyboard.type('quietly')
  await expect(screenplay(page)).toContainText('(quietly)')
  await page.getByRole('button', { name: 'Scene', exact: true }).tap()
  const locations = page.getByRole('dialog', { name: 'Choose a location' })
  await locations.getByRole('button', { name: 'LIGHTHOUSE', exact: true }).tap()
  await expect(screenplay(page)).toBeFocused()
  await page.keyboard.type(' - DAWN')
  await expect(screenplay(page)).toContainText('INT. LIGHTHOUSE - DAWN')
  await page.keyboard.insertText('\n\nMA')
  await page.getByRole('button', { name: 'Complete ↹', exact: true }).tap()
  await expect(screenplay(page)).toContainText('MARA')
  await expect(screenplay(page)).toBeFocused()
})

test('a shrinking visual viewport keeps typing and the comment composer above the keyboard', async ({ page, request }) => {
  await page.addInitScript(() => {
    const viewport = Object.assign(new EventTarget(), { width: 390, height: 844, offsetTop: 0, offsetLeft: 0, pageTop: 0, pageLeft: 0, scale: 1 })
    Object.defineProperty(window, 'visualViewport', { configurable: true, value: viewport })
    window.resizeKeyboardViewport = height => { viewport.height = height; viewport.dispatchEvent(new Event('resize')) }
  })
  await open(page, request)
  await screenplay(page).focus()
  await page.keyboard.press('Control+End')
  await page.evaluate(() => window.resizeKeyboardViewport(380))
  await expect(page.locator('.workspace')).toHaveClass(/keyboard-open/)
  await expect(page.locator('.topbar')).toBeHidden()
  await expect.poll(async () => (await page.locator('.workspace').boundingBox()).height).toBe(380)
  expect((await screenplay(page).boundingBox()).height).toBeGreaterThan(150)
  expect((await page.locator('.statusbar').boundingBox()).y).toBeLessThan(380)
  await page.keyboard.type('Still writing.')
  await page.getByRole('button', { name: 'Add comment', exact: true }).tap()
  const comment = page.getByRole('dialog', { name: 'New line comment' })
  await expect(comment).toBeVisible()
  await comment.locator('textarea').fill('A note from the phone.')
  const box = await comment.boundingBox()
  expect(box.y).toBeGreaterThanOrEqual(0)
  expect(box.y + box.height).toBeLessThanOrEqual(380)
  expect(await comment.locator('textarea').evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16)
  await page.screenshot({ path: '/tmp/screenwriter/screenwriter-phone-keyboard.png', animations: 'disabled' })
  await comment.getByRole('button', { name: 'Post comment' }).tap()
  await expect(page.getByText('A note from the phone.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close comment', exact: true }).tap()
  await page.evaluate(() => window.resizeKeyboardViewport(844))
  await expect(page.locator('.topbar')).toBeVisible()
})

test('phone offline state warns, exports proposed writing, and confirms sync before reload', async ({ page, context, request }) => {
  await open(page, request)
  await page.evaluate(() => navigator.serviceWorker.ready)
  await page.getByRole('button', { name: 'Open tools', exact: true }).tap()
  const tools = page.getByRole('dialog', { name: 'Workspace tools' })
  await tools.getByRole('button', { name: 'Suggest edits', exact: true }).tap()
  await tools.getByRole('button', { name: 'Close tools', exact: true }).tap()
  await screenplay(page).focus()
  await page.keyboard.press('Control+End')
  const marker = `Phone draft ${Date.now()}`
  await context.setOffline(true)
  await page.evaluate(() => window.dispatchEvent(new Event('offline')))
  await expect(page.locator('.mobile-offline-notice')).toBeVisible()
  await page.keyboard.insertText(marker)
  await expect(page.locator('.inline-suggestion-replacement')).toContainText(marker)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download draft', exact: true }).tap()
  const download = await downloadEvent
  expect(await readFile(await download.path(), 'utf8')).toContain(marker)
  await context.setOffline(false)
  await page.evaluate(() => window.dispatchEvent(new Event('online')))
  await expect(page.locator('.mobile-offline-notice')).toBeHidden()
  await page.reload()
  await expect(page.locator('.inline-suggestion-replacement')).toContainText(marker)
})
